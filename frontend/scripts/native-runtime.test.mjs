import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { nativeRuntime } from './native-runtime.mjs';
test('native fingerprint is stable before and after sync, while actual native edits change it',()=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'lw-runtime-'));
 const write=(name,content)=>{const file=path.join(root,name);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,content)};
 try {
  for(const file of ['capacitor.config.ts','android/build.gradle','android/variables.gradle','android/capacitor.settings.gradle','android/app/capacitor.build.gradle','android/app/src/main/AndroidManifest.xml','android/app/src/main/res/xml/file_paths.xml','android/app/src/main/java/MainActivity.java'])write(file,'native source');
  write('android/app/build.gradle','versionCode 2');write('package-lock.json',JSON.stringify({packages:{'node_modules/@capacitor/core':{version:'8.0.0'}}}));
  const before=nativeRuntime(root);
  write('android/app/src/main/res/xml/config.xml','generated by cap sync');
  assert.deepEqual(nativeRuntime(root),before);
  write('android/app/src/main/java/MainActivity.java','changed native source');
  assert.notEqual(nativeRuntime(root).nativeFingerprint,before.nativeFingerprint);
  assert.equal(before.nativeVersionCode,2);
 }finally{fs.rmSync(root,{recursive:true,force:true})}
});
